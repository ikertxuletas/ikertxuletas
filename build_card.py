def gh(path, wait=False) -> Any:
    for _ in range(6 if wait else 1):
        out = subprocess.run(["gh", "api", path], capture_output=True, text=True, encoding="utf-8").stdout
        if out.strip() and out.strip() != "{}":
            return json.loads(out)
        if wait:
            time.sleep(4)  # stats endpoints return 202 while GitHub computes them
    return None


def collect():
    repos = [r for r in gh("user/repos?affiliation=owner&per_page=100") if r["name"] not in EXCLUDED and not r["fork"]]
    weekly = [0] * 52
    per_repo: dict[str, int] = {}
    added = removed = 0
    langs: dict[str, int] = {}
    for r in repos:
        name = r["full_name"]
        series = (gh(f"repos/{name}/stats/participation", wait=True) or {}).get("all", [])
        for i, n in enumerate(series):
            weekly[i] += n
        per_repo[r["name"]] = sum(series)
        for week in gh(f"repos/{name}/stats/code_frequency", wait=True) or []:
            added += week[1]
            removed -= week[2]
        for lang, size in (gh(f"repos/{name}/languages") or {}).items():
            langs[lang] = langs.get(lang, 0) + size
    public = sum(1 for r in repos if not r["private"])
    return dict(repos=len(repos), public=public, weekly=weekly, per_repo=per_repo,
                added=added, removed=removed, langs=langs)


def label(x, y, s, c, anchor="start"):
    return (f'<text x="{x}" y="{y}" font-family="{SANS}" font-size="11" font-weight="600" letter-spacing="1.4" '
            f'fill="{c["accent"]}" text-anchor="{anchor}">{escape(s.upper())}</text>')


def text(x, y, s, c, size=13, color="ink", anchor="start", family=SANS, style="normal"):
    return (f'<text x="{x}" y="{y}" font-family="{family}" font-size="{size}" font-style="{style}" '
            f'fill="{c[color]}" text-anchor="{anchor}" style="font-variant-numeric: tabular-nums">{escape(s)}</text>')


def rule(x0, x1, y, c, color="rule"):
    return f'<path d="M{x0} {y:.1f} H{x1}" stroke="{c[color]}" stroke-width="1"/>'


def performance(d, c, x0, x1, y0, y1):
    weekly = d["weekly"]
    first = next((i for i, n in enumerate(weekly) if n), 0)
    weeks = weekly[max(0, first - 2):]
    today = dt.date.today()
    dates = [today - dt.timedelta(weeks=len(weeks) - 1 - i) for i in range(len(weeks))]
    step = max(10, math.ceil(max(weeks) / 4 / 10) * 10)
    top = step * 4
    xs = [x0 + (x1 - x0) * i / (len(weeks) - 1) for i in range(len(weeks))]
    ys = [y1 - (y1 - y0) * n / top for n in weeks]
    out = []
    for k in range(5):
        y = y1 - (y1 - y0) * k / 4
        out.append(rule(x0, x1, y, c, "rule" if k == 0 else "faint"))
        out.append(text(x1 + 8, y + 4, str(step * k), c, 11, "muted"))
    pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys))
    out.append(f'<polygon points="{x0},{y1} {pts} {x1},{y1}" fill="{c["accent"]}" fill-opacity="0.10"/>')
    out.append(f'<polyline points="{pts}" fill="none" stroke="{c["accent"]}" stroke-width="2" stroke-linejoin="round"/>')
    for i, day in enumerate(dates):
        if i == 0 or day.month != dates[i - 1].month:
            out.append(text(f"{xs[i]:.1f}", y1 + 18, f"{day:%b}", c, 11, "muted"))
    peak = max(range(len(weeks)), key=lambda i: weeks[i])
    out.append(f'<circle cx="{xs[peak]:.1f}" cy="{ys[peak]:.1f}" r="3" fill="{c["accent"]}"/>')
    out.append(text(f"{xs[peak] - 8:.1f}", f"{ys[peak] - 2:.1f}", f"peak {weeks[peak]} / week", c, 11, "muted", "end"))
    return out, dates[0]


def allocation(d, c, x0, x1, y):
    total = sum(d["langs"].values())
    items = sorted(d["langs"].items(), key=lambda item: -item[1])
    main = [(k, v / total) for k, v in items[:3]]
    main.append(("Other", 1 - sum(s for _, s in main)))
    out, x = [], x0
    for i, (_, share) in enumerate(main):
        w = (x1 - x0) * share
        out.append(f'<rect x="{x:.1f}" y="{y}" width="{max(w - 2, 1):.1f}" height="12" fill="{c["shades"][i]}"/>')
        x += w
    lx = x0
    for i, (lang, share) in enumerate(main):
        caption = f"{lang} {share:.0%}"
        out.append(f'<rect x="{lx:.1f}" y="{y + 26}" width="9" height="9" fill="{c["shades"][i]}"/>')
        out.append(text(f"{lx + 15:.1f}", y + 35, caption, c, 12, "muted"))
        lx += 15 + 6.8 * len(caption) + 26
    return out


def holdings(d, c, x0, x1, y):
    total = sum(d["per_repo"].values()) or 1
    rows = sorted(((DISPLAY.get(k, k), v / total) for k, v in d["per_repo"].items()), key=lambda r: -r[1])
    rows = [r for r in rows if r[1] > 0 and r[0] != "This profile"][:5]
    out = []
    for i, (name, share) in enumerate(rows):
        yy = y + 24 * i
        out.append(text(x0, yy, name, c, 13))
        out.append(f'<rect x="{x1 - 160}" y="{yy - 9}" width="{max(1.0, 100 * share):.1f}" height="8" fill="{c["accent"]}"/>')
        out.append(text(x1, yy, f"{share:.1%}", c, 13, anchor="end"))
        out.append(rule(x0, x1, yy + 9, c, "faint"))
    return out


def render(name, c, d):
    today = dt.date.today()
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">',
         f'<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="10" fill="{c["bg"]}" stroke="{c["rule"]}"/>',
         f'<path d="M10 .5 H{W - 10}" stroke="{c["accent"]}" stroke-width="4"/>']
    o.append(label(36, 44, "Factsheet · Python & automation for finance", c))
    o.append(text(36, 82, "Iker González Rodríguez-Priego", c, 30, family=SERIF))
    o.append(text(W - 36, 44, f"As of {today:%d %b %Y}", c, 12, "muted", "end"))
    o.append(text(W - 36, 82, "github.com/ikertxuletas", c, 13, "muted", "end"))
    o.append(rule(36, W - 36, 102, c))
    o.append(text(36, 134, "Strategy: long Python, SQL and scheduled jobs; short manual copy-paste.", c, 16, family=SERIF, style="italic"))

    lx0, lx1, rx0, rx1 = 36, 596, 650, W - 36
    chart, since = performance(d, c, lx0, lx1 - 30, 196, 356)
    o.append(label(lx0, 174, f"Performance · commits per week since {since:%b %Y}", c))
    o += chart
    o.append(label(lx0, 414, "Allocation · languages across all repos", c))
    o += allocation(d, c, lx0, lx1, 430)

    o.append(label(rx0, 174, "Holdings · share of commits, 12 months", c))
    o += holdings(d, c, rx0, rx1, 202)
    o.append(label(rx0, 334, "Key facts", c))
    facts = [("Repositories", f"{d['repos']} ({d['public']} public)"),
             ("Commits, 12 months", f"{sum(d['weekly']):,}"),
             ("Lines added / removed", f"{d['added'] / 1000:,.0f}k / {d['removed'] / 1000:,.0f}k")] + KEY_FACTS
    for i, (k, v) in enumerate(facts):
        y = 356 + 18 * i
        o.append(text(rx0, y, k, c, 12, "muted"))
        o.append(text(rx1, y, v, c, 12, anchor="end"))

    o.append(rule(36, W - 36, H - 40, c))
    o.append(text(36, H - 18, "Source: GitHub API, all repositories including private ones. Past commits are no guarantee of future commits.", c, 11, "muted"))
    o.append("</svg>")
    (ASSETS / f"card-{name}.svg").write_text("\n".join(o), encoding="utf-8")


if __name__ == "__main__":
    data: dict[str, Any] = collect()
    for theme, colors in THEMES.items():
        render(theme, colors, data)
    print(data["per_repo"], "commits:", sum(data["weekly"]))
