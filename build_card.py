def gh(path, wait=False) -> Any:
    for _ in range(6 if wait else 1):
        out = subprocess.run(["gh", "api", path], capture_output=True, text=True, encoding="utf-8").stdout
        if out.strip() and out.strip() != "{}":
            return json.loads(out)
        if wait:
            time.sleep(4)  # stats endpoints return 202 while GitHub computes them
    return None


def collect():
    repos = [r for r in gh("user/repos?affiliation=owner&per_page=100") if r["name"] not in EXCLUDED and not r["fork"]]
    weekly = [0] * 52
    added = removed = 0
    langs: dict[str, int] = {}
    for r in repos:
        name = r["full_name"]
        for i, n in enumerate((gh(f"repos/{name}/stats/participation", wait=True) or {}).get("all", [])):
            weekly[i] += n
        for week in (gh(f"repos/{name}/stats/code_frequency", wait=True) or []):
            added += week[1]
            removed -= week[2]
        for lang, size in (gh(f"repos/{name}/languages") or {}).items():
            langs[lang] = langs.get(lang, 0) + size
    public = sum(1 for r in repos if not r["private"])
    return dict(repos=len(repos), public=public, weekly=weekly, added=added, removed=removed, langs=langs)


def kv(key, value, c):
    dots = WIDTH - len(key) - len(value) - 4
    return (f'<tspan fill="{c["key"]}">{escape(key)}</tspan>:'
            f'<tspan fill="{c["dots"]}"> {"." * dots} </tspan>'
            f'<tspan fill="{c["value"]}">{escape(value)}</tspan>')


def section(title, c):
    return f'<tspan fill="{c["text"]}">- {title} </tspan><tspan fill="{c["dots"]}">{"─" * (WIDTH - len(title) - 3)}</tspan>'


def left_column(d, c):
    """Weekly commit chart and language split, drawn as SVG in the card's terminal style."""
    weekly = d["weekly"]
    first = next((i for i, n in enumerate(weekly) if n), 0)
    weeks = weekly[max(0, first - 2):]
    today = dt.date.today()
    dates = [today - dt.timedelta(weeks=len(weeks) - 1 - i) for i in range(len(weeks))]
    x0, x1, y0, y1 = 62, 404, 66, 296
    step = max(10, math.ceil(max(weeks) / 4 / 10) * 10)
    top = step * 4
    xs = [x0 + (x1 - x0) * i / (len(weeks) - 1) for i in range(len(weeks))]
    ys = [y1 - (y1 - y0) * n / top for n in weeks]
    out = [f'<text x="22" y="36" font-size="14" fill="{c["text"]}">commits per week since {dates[0]:%b %Y}</text>']
    for k in range(5):
        y = y1 - (y1 - y0) * k / 4
        out.append(f'<path d="M{x0} {y:.1f} H{x1}" stroke="{c["dots"]}" stroke-opacity="{0.6 if k == 0 else 0.25}" stroke-dasharray="{"" if k == 0 else "2 4"}"/>')
        out.append(f'<text x="{x0 - 10}" y="{y + 4:.1f}" font-size="12" text-anchor="end" fill="{c["dots"]}">{step * k}</text>')
    pts = " ".join(f"{x:.1f},{y:.1f}" for x, y in zip(xs, ys))
    out.append(f'<polygon points="{x0},{y1} {pts} {x1},{y1}" fill="{c["key"]}" fill-opacity="0.12"/>')
    out.append(f'<polyline points="{pts}" fill="none" stroke="{c["key"]}" stroke-width="2" stroke-linejoin="round"/>')
    out.append(f'<circle cx="{xs[-1]:.1f}" cy="{ys[-1]:.1f}" r="3.5" fill="{c["key"]}"/>')
    for i, d_ in enumerate(dates):
        if i == 0 or d_.month != dates[i - 1].month:
            out.append(f'<text x="{xs[i]:.1f}" y="{y1 + 20}" font-size="12" fill="{c["dots"]}">{d_:%b}</text>')
    out.append(f'<text x="22" y="362" font-size="14" fill="{c["text"]}">languages across all repos</text>')
    total = sum(d["langs"].values())
    top_langs = [(k, v / total) for k, v in sorted(d["langs"].items(), key=lambda item: -item[1]) if v / total >= 0.01][:4]
    for i, (lang, share) in enumerate(top_langs):
        y = 392 + 26 * i
        out.append(f'<text x="22" y="{y}" font-size="13" fill="{c["value"]}">{lang}</text>')
        out.append(f'<rect x="124" y="{y - 10}" width="232" height="10" rx="2" fill="{c["dots"]}" fill-opacity="0.2"/>')
        out.append(f'<rect x="124" y="{y - 10}" width="{max(2, 232 * share):.1f}" height="10" rx="2" fill="{c["key"]}"/>')
        out.append(f'<text x="404" y="{y}" font-size="13" text-anchor="end" fill="{c["text"]}">{share:.0%}</text>')
    return out


def right_column(d, c):
    lines = [f'<tspan fill="{c["text"]}">{USER}@munich</tspan>', f'<tspan fill="{c["dots"]}">{"─" * WIDTH}</tspan>']
    lines += ["" if row is None else kv(*row, c) for row in INFO]
    lines += ["", section("Contact", c)] + [kv(*row, c) for row in CONTACT]
    lines += ["", section("GitHub Stats", c)]
    lines.append(kv("Repos", f"{d['repos']} {{public: {d['public']}}}", c))
    lines.append(kv("Commits, last 12 months", f"{sum(d['weekly']):,}", c))
    a, r = d["added"], d["removed"]
    plain = f"{a - r:,} ( {a:,}++, {r:,}-- )"
    dots = WIDTH - len("Lines of code") - len(plain) - 4
    lines.append(f'<tspan fill="{c["key"]}">Lines of code</tspan>:<tspan fill="{c["dots"]}"> {"." * dots} </tspan>'
                 f'<tspan fill="{c["value"]}">{a - r:,}</tspan> ( <tspan fill="{c["add"]}">{a:,}++</tspan>, <tspan fill="{c["dele"]}">{r:,}--</tspan> )')
    return lines


def render(name, c, d):
    left, right = left_column(d, c), right_column(d, c)
    h = max(500, 44 + 20 * len(right))
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" font-family="ConsolasFallback, Consolas, \'SF Mono\', Menlo, monospace" width="{CARD_W}" height="{h}" viewBox="0 0 {CARD_W} {h}">',
           '<style>@font-face{src:local("Consolas"),local("Consolas Bold");font-family:"ConsolasFallback";font-display:swap;size-adjust:109%}text,tspan{white-space:pre}</style>',
           f'<rect x=".5" y=".5" width="{CARD_W - 1}" height="{h - 1}" rx="15" fill="{c["bg"]}" stroke="{c["border"]}"/>',
           f'<path d="M{RIGHT_X - 24} 24 V{h - 24}" stroke="{c["border"]}"/>']
    out += left
    out.append(f'<text font-size="16" fill="{c["text"]}">')
    out += [f'<tspan x="{RIGHT_X}" y="{34 + 20 * i}">{line}</tspan>' for i, line in enumerate(right)]
    out.append("</text></svg>")
    (ASSETS / f"card-{name}.svg").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    data: dict[str, Any] = collect()
    for theme, colors in THEMES.items():
        render(theme, colors, data)
    print({k: v for k, v in data.items() if k != "weekly"}, "commits:", sum(data["weekly"]))
